import Foundation

/// The Herdr pane a focuspilot command came from, as its environment claims.
/// Any local process can claim any pane, so this scopes reads for
/// convenience and is not a security boundary.
public struct HerdrCaller: Codable, Equatable, Sendable {
    public var server: HerdrServer
    public var workspaceID: String
    public var paneID: String?

    public init(server: HerdrServer, workspaceID: String, paneID: String?) {
        self.server = server
        self.workspaceID = workspaceID
        self.paneID = paneID
    }
}

/// One `focuspilot add`, as sent to the app or queued in the inbox.
///
/// The text is parsed against the time and zone it was typed in, wherever
/// and whenever it is stored, so a queued "tomorrow" keeps meaning the day
/// after it was typed.
public struct HerdrAddRequest: Codable, Equatable, Sendable {
    /// Generated by the CLI; the same request is never stored twice.
    public var id: UUID
    public var text: String
    public var capturedAt: Date
    public var timeZone: TimeZone
    public var caller: HerdrCaller?

    public init(id: UUID = UUID(), text: String, capturedAt: Date, timeZone: TimeZone, caller: HerdrCaller?) {
        self.id = id
        self.text = text
        self.capturedAt = capturedAt
        self.timeZone = timeZone
        self.caller = caller
    }

    /// The task to store and the notes to print, split the way the capture
    /// sheet splits its one field. A deadline phrase that cannot be read
    /// never blocks: the whole text becomes the title, with the sheet's hint.
    public var capture: (task: NewTask, hints: [String]) {
        let parser = DeadlineParser(now: capturedAt, timeZone: timeZone)
        // No spelling dictionary outside the app: a near-miss hint may name a
        // real word, which is harmless because it never changes the task.
        let split = CaptureSplitter(parser: parser).split(text, isKnownWord: { _ in false })
        if let phrase = split.deadlineText, split.deadline == nil {
            return (NewTask(title: text), [DeadlineParser.hint(for: phrase)])
        }
        let hint = split.unrecognizedWord.map { "Did you mean a date? “\($0)” wasn’t recognized." }
        return (NewTask(title: split.title, deadline: split.deadline), hint.map { [$0] } ?? [])
    }
}

/// What the app reports back for an add.
public struct HerdrAddResult: Codable, Equatable, Sendable {
    public var taskID: Int64
    public var title: String
    public var projectTitle: String?
    /// The caller is in a Herdr workspace that no project is linked to.
    public var workspaceHasNoProject: Bool
    /// `DeadlineText.inspection`, e.g. "Fri 16 Oct 2026, 23:59 · America/Bogota (GMT−5)".
    public var deadlineDescription: String?
    public var hints: [String]
    /// The request had been stored before, by an earlier attempt or import.
    public var wasAlreadyAdded: Bool
}

/// One task as `focuspilot tasks` shows it.
public struct HerdrScopedTask: Codable, Equatable, Sendable {
    public var title: String
    public var status: TaskStatus
    public var nextAction: String?
    public var deadline: String?
    public var isFromHerdr: Bool
}

/// What `focuspilot tasks` may read: the owner's Now, and the open tasks of
/// the caller's linked project.
public struct HerdrTaskScope: Codable, Equatable, Sendable {
    public var now: HerdrScopedTask?
    public var projectTitle: String?
    public var tasks: [HerdrScopedTask]
}

public enum HerdrTaskError: Error, Equatable {
    case notFromHerdr
    /// The owner pinned it; undo is for tasks still waiting in Next or Later.
    case isNow
    case isDone
    case inRunningSession
}
